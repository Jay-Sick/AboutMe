#!/usr/bin/env python3
"""
Jacek Szewczyk // IT Professional Portfolio
Auto-Syncing One-Click Launcher & Local Web Server
Usage: python3 Launch.py (or double-click on Windows)

FEATURES:
- Automatically scans the projects/ directory and populates projects without running sync.py!
- Re-scans dynamically on every page refresh whenever /projects/projects.json is requested.
- Automatically launches your default browser at http://localhost:<port>/index.html
"""

import os
import sys
import glob
import json
import socket
import webbrowser
from http.server import HTTPServer, SimpleHTTPRequestHandler

DEFAULT_PORT = 8000

def sync_projects(base_dir):
    """
    Scans all individual *.json files in projects/ and compiles projects.json & projects.js.
    Runs on server launch and on dynamic browser requests.
    """
    projects_dir = os.path.join(base_dir, "projects")
    if not os.path.isdir(projects_dir):
        return []

    json_files = sorted(glob.glob(os.path.join(projects_dir, "*.json")))
    projects = []

    for filepath in json_files:
        filename = os.path.basename(filepath)
        if filename in ["projects.json", "manifest.json", "MiniMonitor - Copy.json"]:
            continue
        if filename.startswith("writeup-homelab-vlan"):
            continue

        try:
            with open(filepath, "r", encoding="utf-8") as f:
                content = f.read().strip()
                if not content:
                    continue
                data = json.loads(content)
                if not data or not data.get("title") or data.get("disabled"):
                    continue
                projects.append(data)
        except Exception as e:
            pass

    # Separate featured and unfeatured
    featured = [p for p in projects if p.get("featured", False)]
    unfeatured = [p for p in projects if not p.get("featured", False)]

    # Sort featured projects: by featuredOrder ascending if present (< 90), else by date descending
    featured_with_order = [p for p in featured if isinstance(p.get("featuredOrder"), int) and p.get("featuredOrder") < 90]
    featured_without_order = [p for p in featured if not (isinstance(p.get("featuredOrder"), int) and p.get("featuredOrder") < 90)]

    featured_with_order.sort(key=lambda p: p.get("featuredOrder", 999))
    featured_without_order.sort(key=lambda p: str(p.get("startDate", p.get("date", ""))), reverse=True)
    featured = featured_with_order + featured_without_order

    # Sort unfeatured projects strictly by date descending
    unfeatured.sort(key=lambda p: (
        str(p.get("startDate", p.get("date", ""))),
        str(p.get("id", ""))
    ), reverse=True)

    sorted_projects = featured + unfeatured

    # Write compiled projects.json & projects.js
    out_json = os.path.join(projects_dir, "projects.json")
    try:
        with open(out_json, "w", encoding="utf-8") as f:
            json.dump(sorted_projects, f, indent=2)
    except Exception:
        pass

    out_js = os.path.join(projects_dir, "projects.js")
    try:
        with open(out_js, "w", encoding="utf-8") as f:
            f.write("/** Autogenerated projects registry for Jacek Szewczyk's Portfolio. */\n")
            f.write(f"window.PROJECTS_DATA = {json.dumps(sorted_projects, indent=2)};\n")
    except Exception:
        pass

    return sorted_projects

class DynamicPortfolioHandler(SimpleHTTPRequestHandler):
    """
    Custom request handler that automatically re-scans the projects folder
    whenever projects.json is requested, so you never need to run sync.py!
    """
    def do_GET(self):
        # Intercept projects.json request to serve fresh dynamically compiled data
        clean_path = self.path.split("?")[0]
        if clean_path in ["/projects/projects.json", "/api/projects"]:
            base_dir = os.path.dirname(os.path.abspath(__file__))
            latest_projects = sync_projects(base_dir)
            json_bytes = json.dumps(latest_projects, indent=2).encode("utf-8")

            self.send_response(200)
            self.send_header("Content-Type", "application/json; charset=utf-8")
            self.send_header("Content-Length", str(len(json_bytes)))
            self.send_header("Cache-Control", "no-cache, no-store, must-revalidate")
            self.send_header("Pragma", "no-cache")
            self.send_header("Expires", "0")
            self.end_headers()
            self.wfile.write(json_bytes)
            return

        # Serve other static files normally
        super().do_GET()

def find_free_port(start_port):
    port = start_port
    while port < start_port + 100:
        with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as s:
            if s.connect_ex(('127.0.0.1', port)) != 0:
                return port
            port += 1
    return start_port

def run_server():
    base_dir = os.path.dirname(os.path.abspath(__file__))
    os.chdir(base_dir)

    # Initial sync on server launch
    initial_projects = sync_projects(base_dir)
    port = find_free_port(DEFAULT_PORT)
    url = f"http://localhost:{port}/index.html"

    print("=" * 68)
    print("  JACEK SZEWCZYK // IT PROFESSIONAL PORTFOLIO")
    print("=" * 68)
    print(f"  [+] Server Root      : {base_dir}")
    print(f"  [+] Local URL        : {url}")
    print(f"  [+] Loaded Projects  : {len(initial_projects)} active projects detected")
    print("  [+] Auto-Sync Mode   : ACTIVE (No need to run sync.py!)")
    print("  [!] Press Ctrl+C anytime to stop the server.")
    print("=" * 68)

    # Automatically launch default browser
    try:
        webbrowser.open(url)
        print("  [✔] Default browser opened automatically.")
    except Exception as e:
        print(f"  [!] Note: Could not auto-launch browser ({e}). Open {url} manually.")

    # Start HTTP server with dynamic request handler
    try:
        with HTTPServer(('127.0.0.1', port), DynamicPortfolioHandler) as httpd:
            httpd.serve_forever()
    except KeyboardInterrupt:
        print("\n  [✔] Server shut down gracefully. Goodbye!")
        sys.exit(0)

if __name__ == '__main__':
    run_server()
