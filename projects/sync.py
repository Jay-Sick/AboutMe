#!/usr/bin/env python3
"""
Sync Script for Jacek Szewczyk's Portfolio Projects.
Scans all individual *.json files in this folder and rebuilds projects.json and projects.js automatically.
Usage: python3 sync.py
"""

import os
import json
import glob

def sync_projects():
    base_dir = os.path.dirname(os.path.abspath(__file__))
    json_files = sorted(glob.glob(os.path.join(base_dir, "*.json")))
    
    projects = []
    for filepath in json_files:
        filename = os.path.basename(filepath)
        if filename in ["projects.json", "manifest.json"]:
            continue
        try:
            with open(filepath, "r", encoding="utf-8") as f:
                data = json.load(f)
                projects.append(data)
                print(f"[+] Loaded project: {data.get('title', filename)} ({filename})")
        except Exception as e:
            print(f"[!] Warning: failed to parse {filename}: {e}")

    # Write centralized projects.json
    out_json = os.path.join(base_dir, "projects.json")
    with open(out_json, "w", encoding="utf-8") as f:
        json.dump(projects, f, indent=2)
    print(f"[✔] Successfully compiled {len(projects)} projects into {out_json}")

    # Write projects.js for offline file:// preview compatibility
    out_js = os.path.join(base_dir, "projects.js")
    with open(out_js, "w", encoding="utf-8") as f:
        f.write("/** Autogenerated projects registry for Jacek Szewczyk's Portfolio. */\n")
        f.write(f"window.PROJECTS_DATA = {json.dumps(projects, indent=2)};\n")
    print(f"[✔] Successfully generated {out_js}")

if __name__ == "__main__":
    sync_projects()
