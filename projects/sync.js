#!/usr/bin/env node
/**
 * Node.js Sync Script for Jacek Szewczyk's Portfolio Projects.
 * Scans all individual *.json files in this folder and rebuilds projects.json and projects.js.
 * Usage: node sync.js
 */

const fs = require('fs');
const path = require('path');

const baseDir = __dirname;
const files = fs.readdirSync(baseDir).filter(f => f.endsWith('.json') && f !== 'projects.json' && f !== 'manifest.json');

const projects = files.map(file => {
  const content = fs.readFileSync(path.join(baseDir, file), 'utf8');
  const parsed = JSON.parse(content);
  console.log(`[+] Loaded: ${parsed.title || file}`);
  return parsed;
});

// Write projects.json
fs.writeFileSync(path.join(baseDir, 'projects.json'), JSON.stringify(projects, null, 2));
console.log(`[✔] Saved ${projects.length} projects to projects.json`);

// Write projects.js for file:// browser support
const jsContent = `/** Autogenerated projects registry */\nwindow.PROJECTS_DATA = ${JSON.stringify(projects, null, 2)};\n`;
fs.writeFileSync(path.join(baseDir, 'projects.js'), jsContent);
console.log('[✔] Saved projects.js');
